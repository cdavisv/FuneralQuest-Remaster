const GENERATED_FROM = (what: string): string =>
  ` Generated by 'pnpm --filter @fq/content run import' from ${what}.\n The original 2001 text must remain (CLAUDE.md): do not edit this file. The build fails if it\n differs from a fresh import, or if packs/classic has an overrides file.`;

/** The text of every file of a pack's source directory, by file name. Pure. */
export function renderSourcePack(pack: ContentPack): Record<string, string> {
  const files: Record<string, string> = {};
  files["pack.yaml"] = toYaml({ id: pack.id });
  for (const table of TABLE_KEYS) {
    const value =
      table === "ratings" || table === "karma" ? slotsToRecord(pack[table]) : pack[table];
    const from =
      table === "text"
        ? "CLASSIC_TEXT in packages/core/src/content/classicText.ts"
        : `legacy/dist/${LEGACY_FILE[table]}`;
    files[`${TABLE_FILE[table]}.yaml`] = toYaml(value, GENERATED_FROM(from));
  }
  return files;
}

export function writeFiles(dir: string, files: Record<string, string>): void {
  mkdirSync(dir, { recursive: true });
  for (const [name, text] of Object.entries(files)) writeFileSync(join(dir, name), text);
}

const BUILT_IN = ["vintage", "classic", "expanded"] as const;
type BuiltInName = (typeof BUILT_IN)[number];

const packMetaSchema = z
  .strictObject({
    id: z.string(),
    extends: z.enum(BUILT_IN).optional(),
    /**
     * How a table file combines with the pack it extends. `replace` (the default): the file is the
     * whole table. `append`: the file adds to the base table (merge.ts says how, per table kind).
     */
    merge: z.enum(["replace", "append"]).optional(),
  })
  .refine((m) => m.merge !== "append" || m.extends !== undefined, {
    error: "merge: append needs 'extends' (there is nothing to append to)",
  });

export interface LoadOptions {
  /** Known asset ids; when given every picture must be in it. */
  assetIds?: ReadonlySet<string>;
  /** Pack to use for `extends` (default: the built-in pack of that name). */
  base?: ContentPack;
  /**
   * Refuse a directory that has an overrides file. The built-in packs load with this on: an
   * override is an edit to a line of the pack it extends, and the original text must remain.
   */
  forbidOverrides?: boolean;
}

/**
 * A built-in pack for `extends`. It comes from the bundled JSON module, not from `built/` on disk,
 * so a server bundle (which has no `built/` directory next to it) can load custom packs too.
 */
function readBuiltPack(name: BuiltInName): ContentPack {
  return name === "vintage" ? vintagePack : name === "classic" ? classicPack : expandedPack;
}

function findTableFile(dir: string, table: TableKey): string | undefined {
  const found = ["yaml", "yml", "json"]
    .map((ext) => join(dir, `${TABLE_FILE[table]}.${ext}`))
    .filter((p) => existsSync(p));
  if (found.length > 1) {
    throw new Error(
      `${dir}: ${found.length} files for table '${table}' (${found.join(", ")}); keep one`,
    );
  }
  return found[0];
}

function readStructured(path: string): unknown {
  return fromYaml(readFileSync(path, "utf8"), path);
}

const STRUCTURED = /^(.*)\.(ya?ml|json)$/;

/**
 * Reads a directory tree as one object: `a.yaml` is key `a`, a subdirectory `b/` is key `b` (an
 * object built the same way). A key given both as a file and as a directory is an error.
 */
function readTree(dir: string): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    const isDir = statSync(path).isDirectory();
    const key = isDir ? name : STRUCTURED.exec(name)?.[1];
    if (key === undefined) continue;
    if (key in out) throw new Error(`${path}: '${key}' is given twice; keep one`);
    out[key] = isDir ? readTree(path) : readStructured(path);
  }
  return out;
}

/** The Expanded section of a pack directory: `expanded/` (a tree) or `expanded.yaml`, if any. */
function readExpanded(dir: string): { value: unknown; file: string } | undefined {
  const tree = join(dir, EXPANDED_KEY);
  const single = ["yaml", "yml", "json"]
    .map((ext) => join(dir, `${EXPANDED_KEY}.${ext}`))
    .filter((p) => existsSync(p));
  const hasTree = existsSync(tree) && statSync(tree).isDirectory();
  if (single.length + (hasTree ? 1 : 0) > 1) {
    throw new Error(`${dir}: the Expanded section is given more than once; keep one`);
  }
  if (hasTree) return { value: readTree(tree), file: `${basename(dir)}/${EXPANDED_KEY}/` };
  const path = single[0];
  return path
    ? { value: readStructured(path), file: `${basename(dir)}/${basename(path)}` }
    : undefined;
}

/**
 * Loads a pack from a directory, for sysops and mods. The directory holds `pack.yaml`
 * (`id`, and optionally `extends: classic | expanded`, or the deprecated `vintage`), one file per table named after the legacy file
 * (`events.yaml`, `news_blurbs.yaml`, `no_customers.yaml`, `yangs.yaml`, `yangs_nice.yaml`,
 * `risks.yaml`, `soft_sell.yaml`, `hard_sell.yaml`, `ratings.yaml`, `karma.yaml`, `text.yaml`;
 * `.yml` and `.json` work too) and optionally `overrides.yaml` (text edits for a sysop's own pack;
 * the built-in packs have none and may not). `extends: vintage` is the deprecated name of `classic`.
 * A pack that `extends` another only needs the tables it replaces; with `merge: append` its table
 * files add to the base's instead (merge.ts). The Expanded section is `expanded.yaml` or a directory
 * `expanded/` with one file per key (tables.ts `EXPANDED_KEY`); without one it is inherited. The
 * result is validated; any problem throws with the file and entry named.
 */
export function loadPackFromDirectory(dir: string, options: LoadOptions = {}): ContentPack {
  const metaPath = join(dir, "pack.yaml");
  if (!existsSync(metaPath)) throw new Error(`${dir}: pack.yaml is missing (it holds the pack id)`);
  const metaResult = packMetaSchema.safeParse(readStructured(metaPath));
  if (!metaResult.success) {
    throw new Error(
      `${metaPath}: ${metaResult.error.issues.map((i) => `${i.path.join(".") || "pack"}: ${i.message}`).join("; ")}`,
    );
  }
  const meta = metaResult.data;
  const base = options.base ?? (meta.extends ? readBuiltPack(meta.extends) : undefined);

  const append = meta.merge === "append";
  const files: Partial<Record<TableKey | "pack" | typeof EXPANDED_KEY, string>> = {
    pack: `${basename(dir)}/pack.yaml`,
  };
  const loaded: Record<string, unknown> = { id: meta.id };
  for (const table of TABLE_KEYS) {
    const path = findTableFile(dir, table);
    if (path === undefined) {
      if (!base) {
        throw new Error(
          `${dir}: ${TABLE_FILE[table]}.yaml is missing (and pack.yaml has no 'extends')`,
        );
      }
      loaded[table] = structuredClone(base[table]);
      files[table] =
        `${basename(dir)}/${TABLE_FILE[table]}.yaml (inherited from ${meta.extends ?? "base"})`;
      continue;
    }
    const raw = readStructured(path);
    if (append && base) {
      loaded[table] = appendTable(table, base[table], raw, path);
    } else {
      loaded[table] = table === "ratings" || table === "karma" ? recordToSlots(raw, path) : raw;
    }
    files[table] =
      `${basename(dir)}/${basename(path)}${append ? ` (appended to ${meta.extends})` : ""}`;
  }
  const expanded = readExpanded(dir);
  if (expanded) {
    loaded[EXPANDED_KEY] = expanded.value;
    files[EXPANDED_KEY] = expanded.file;
  } else if (base?.expanded) {
    loaded[EXPANDED_KEY] = structuredClone(base.expanded);
    files[EXPANDED_KEY] =
      `${basename(dir)}/${EXPANDED_KEY}/ (inherited from ${meta.extends ?? "base"})`;
  }

  const issues = checkPack(loaded, {
    files,
    ...(options.assetIds ? { assetIds: options.assetIds } : {}),
  });
  if (issues.length > 0) throw new PackValidationError(meta.id, issues);
  let pack = loaded as unknown as ContentPack;

  const overridesPath = ["overrides.yaml", "overrides.yml", "overrides.json"]
    .map((n) => join(dir, n))
    .find((p) => existsSync(p));
  if (overridesPath && options.forbidOverrides) {
    throw new PackValidationError(meta.id, [
      {
        file: `${basename(dir)}/${basename(overridesPath)}`,
        path: "",
        message:
          "a built-in pack may not have an overrides file: the original game text must remain unchanged (CLAUDE.md)",
        kind: "original",
      },
    ]);
  }
  if (overridesPath) {
    const parsed = overridesFileSchema.safeParse(readStructured(overridesPath));
    if (!parsed.success) {
      throw new Error(
        `${overridesPath}:\n${parsed.error.issues.map((i) => `  - ${i.path.join(".")}: ${i.message}`).join("\n")}`,
      );
    }
    pack = applyOverrides(pack, parsed.data.edits, meta.id);
    const after = checkPack(pack, {
      files,
      ...(options.assetIds ? { assetIds: options.assetIds } : {}),
    });
    if (after.length > 0) throw new PackValidationError(meta.id, after);
  }
  return pack;
}

/** Where the built-in packs are read from. Tests point these at planted copies. */
export interface BuiltInDirs {
  classic?: string;
  expanded?: string;
}

/**
 * The built-in packs, loaded from their source directories. Classic is read from `packs/classic`
 * (the imported original), Vintage is the same data under its old id, and Expanded extends
 * Classic. No built-in pack may have an overrides file: the original text must remain.
 */
export function loadBuiltInSources(
  options: { assetIds?: ReadonlySet<string>; dirs?: BuiltInDirs } = {},
): {
  vintage: ContentPack;
  classic: ContentPack;
  expanded: ContentPack;
} {
  const assets = options.assetIds ? { assetIds: options.assetIds } : {};
  const classic = loadPackFromDirectory(options.dirs?.classic ?? CLASSIC_DIR, {
    ...assets,
    forbidOverrides: true,
  });
  const expanded = loadPackFromDirectory(options.dirs?.expanded ?? EXPANDED_DIR, {
    ...(options.assetIds ? { assetIds: expandedAssetIds(options.assetIds) } : {}),
    base: classic,
    forbidOverrides: true,
  });
  // Deprecated alias: `vintage` names the same data as `classic` (builtin.ts).
  const vintage: ContentPack = { ...classic, id: "vintage" };
  return { vintage, classic, expanded };
}

/**
 * The single JSON module for each built-in pack, built from the source directories. The build
 * fails, with every problem listed, unless:
 *
 * - every built-in pack keeps every line of the original game text unchanged, measured against a
 *   fresh import of `legacy/dist` and `CLASSIC_TEXT` (`checkOriginal`, original.ts): Classic and
 *   Vintage must be identical to it, Expanded may only add;
 * - the Expanded pack passes the content lint (lint.ts), which holds only its new text to the
 *   content policy.
 */
export function renderBuiltPacks(
  options: { assetIds?: ReadonlySet<string>; dirs?: BuiltInDirs } = {},
): Record<string, string> {
  const { vintage, classic, expanded } = loadBuiltInSources(options);
  const original = importOriginal(options.assetIds ? { assetIds: options.assetIds } : {}).pack;
  for (const [pack, exact] of [
    [classic, true],
    [vintage, true],
    [expanded, false],
  ] as const) {
    const issues = checkOriginal(pack, original, { exact });
    if (issues.length > 0) throw new PackValidationError(pack.id, issues);
  }
  const lintOptions: LintOptions = {
    original,
    ...(options.assetIds ? { assetIds: expandedAssetIds(options.assetIds) } : {}),
  };
  const problems = lintPack(expanded, lintOptions);
  if (problems.length > 0) throw new PackValidationError(expanded.id, problems);
  return {
    "vintage.json": `${JSON.stringify(vintage, null, 2)}\n`,
    "classic.json": `${JSON.stringify(classic, null, 2)}\n`,
    "expanded.json": `${JSON.stringify(expanded, null, 2)}\n`,
  };
}
