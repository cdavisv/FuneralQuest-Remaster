export const PACKAGE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const REPO_ROOT = resolve(PACKAGE_ROOT, "../..");
export const LEGACY_DIST = join(REPO_ROOT, "legacy/dist");
export const MANIFEST_PATH = join(REPO_ROOT, "assets/manifest.json");
/** The Classic pack: the original text, imported from `legacy/dist` (there is no other source). */
export const CLASSIC_DIR = join(PACKAGE_ROOT, "packs/classic");
export const EXPANDED_DIR = join(PACKAGE_ROOT, "packs/expanded");
export const BUILT_DIR = join(PACKAGE_ROOT, "built");

/** Ids in `assets/manifest.json`. */
export function loadAssetIds(manifestPath: string = MANIFEST_PATH): Set<string> {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as { assets: { id: string }[] };
  return new Set(manifest.assets.map((a) => a.id));
}

export const REMASTERED_MANIFEST_PATH = join(REPO_ROOT, "assets/remastered/manifest.json");

/**
 * Ids in `assets/remastered/manifest.json` (the Remastered art pack). They exist only in that pack,
 * so only the Expanded pack may use them; the client falls back across packs for the rest.
 */
export function loadRemasteredAssetIds(
  manifestPath: string = REMASTERED_MANIFEST_PATH,
): Set<string> {
  return loadAssetIds(manifestPath);
}

/**
 * The picture ids the Expanded pack may use: the Classic manifest's, or the Remastered one's.
 * Vintage and Classic are checked against the Classic manifest alone.
 */
export function expandedAssetIds(classicIds: ReadonlySet<string>): Set<string> {
  return new Set([...classicIds, ...loadRemasteredAssetIds()]);
}

/** The legacy files, decoded as ISO-8859-1 (each byte is one character, as in the C++). */
export function readLegacySources(distDir: string = LEGACY_DIST): LegacySources {
  const out: Record<string, string> = {};
  for (const file of Object.values(LEGACY_FILE)) {
    out[file] = readFileSync(join(distDir, file), "latin1");
  }
  return out as LegacySources;
}

/**
 * Imports the original game text from the legacy files and `CLASSIC_TEXT`. This is the Classic
 * pack (id `classic`): nothing is added to it or taken out, and `checkOriginal` (original.ts)
 * measures every built-in pack against a fresh run of this function.
 */
export function importOriginal(
  options: { distDir?: string; assetIds?: ReadonlySet<string> } = {},
): {
  pack: ContentPack;
  notes: ImportNote[];
} {
  const { tables, notes } = importLegacyTables(readLegacySources(options.distDir), {
    ...(options.assetIds ? { assetIds: options.assetIds } : {}),
  });
  return { pack: { id: "classic", ...tables, text: structuredClone(CLASSIC_TEXT) }, notes };
}

