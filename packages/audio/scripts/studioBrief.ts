/**
 * The Studio pack's brief: for every track, the text prompt sent to ElevenLabs, the model and
 * its parameters, where the track plays in the game, and what the post-production and the checks
 * expect of it. `studio.ts` reads this with `assets/audio-studio/takes.json` (which generation
 * was made from each prompt, what it cost, which take was chosen) and writes the pack.
 *
 * House style for the whole pack: dry and slightly comic, small-town, never horror, never epic.
 * Music: a funeral-parlor reed or pipe organ at the heart, banjo and upright bass, a little
 * spooky lounge (theremin, vibraphone, brushed drums). Instrumental only.
 */
import type { TrackKind } from "../src/tracks.js";

export const MUSIC_MODEL = "eleven_music_v2_5";
export const SFX_MODEL = "eleven_text_to_sound_v2";

export interface BriefEntry {
  id: string;
  kind: Exclude<TrackKind, "ui">;
  title: string;
  /** Where it plays in the game (for the listening page). */
  where: string;
  model: typeof MUSIC_MODEL | typeof SFX_MODEL;
  prompt: string;
  /** Model parameters exactly as sent. */
  params: Record<string, number | boolean | string>;
  /** Music: the tempo and metre asked for (the beat tracker's prior) and the key. */
  bpm?: number;
  beatsPerBar?: number;
  key?: string;
  /** Loops: the period wanted, seconds (the Synth pack's length), or an exact bar count. */
  loopSeconds?: number;
  loopBars?: number;
  /** One-shots: the longest the delivered file may be (a fade closes anything longer). */
  maxSeconds?: number;
  /** Effects: the onset count the sound should have, [min, max]. */
  onsets?: [number, number];
  /**
   * Ambience with a pulse (a clock, a heart monitor): cut the loop on the pulse like music, at
   * this rate (beats per minute, the tracker's prior) and grouping, about `loopSeconds` long.
   */
  pulse?: { bpm: number; beatsPerBar: number };
}

const instrumental = (seconds: number) => ({
  duration_seconds: seconds,
  instrumental: true,
  lyrics_type: "instrumental",
});
const sfx = (seconds: number, influence = 0.6) => ({
  duration_seconds: seconds,
  prompt_influence: influence,
  loop: false,
});
const amb = (seconds: number) => ({
  duration_seconds: seconds,
  prompt_influence: 0.5,
  loop: true,
});

