interface Placement {
  parent: string;
  depth: number;
  frame: number;
  name: string | undefined;
  at: [number, number];
}

export interface SpriteNames {
  /** Instance names under which each character is placed. */
  names: Map<number, Set<string>>;
  placements: Map<number, Placement[]>;
}

export function collectPlacements(swf: Swf): SpriteNames {
  const names = new Map<number, Set<string>>();
  const placements = new Map<number, Placement[]>();
  const scan = (tl: TimelineData, parent: string): void => {
    tl.frames.forEach((f, fi) => {
      for (const c of f.cmds) {
        if (c.op !== "place" || c.charId === undefined) continue;
        if (c.name) {
          const set = names.get(c.charId) ?? new Set<string>();
          set.add(c.name);
          names.set(c.charId, set);
        }
        const list = placements.get(c.charId) ?? [];
        list.push({
          parent,
          depth: c.depth,
          frame: fi + 1,
          name: c.name,
          at: [(c.matrix?.[4] ?? 0) / 20, (c.matrix?.[5] ?? 0) / 20],
        });
        placements.set(c.charId, list);
      }
    });
  };
  scan(swf.root, "root");
  for (const [id, ch] of swf.characters)
    if (ch.type === "sprite") scan(ch.timeline, `sprite ${id}`);
  return { names, placements };
}

export function describeSprite(id: number, sn: SpriteNames): string {
  const n = sn.names.get(id);
  return n ? `sprite ${id} (${[...n].join(", ")})` : `sprite ${id}`;
}

const COND_EVENTS: [number, string][] = [
  [0x001, "rollOver"],
  [0x002, "rollOut"],
  [0x004, "press"],
  [0x008, "release"],
  [0x010, "dragOut"],
  [0x020, "dragOver"],
  [0x040, "releaseOutside"],
  [0x080, "rollOver (from pressed)"],
  [0x100, "rollOut (while pressed)"],
];

function condText(cond: number): string {
  const ev = COND_EVENTS.filter(([b]) => cond & b).map(([, n]) => n);
  const key = (cond >> 9) & 0x7f;
  if (key) ev.push(`keyPress ${key}`);
  return ev.join(", ") || "none";
}

const _indent = (s: string): string =>
  s
    .split("\n")
    .map((l) => (l ? `  ${l}` : l))
    .join("\n");

/** Markdown listing of every action in the movie, in timeline order. */
export function actionScriptListing(swf: Swf, fileName: string): string {
  const sn = collectPlacements(swf);
  const out: string[] = [];
  out.push(`# ${fileName}: decompiled ActionScript 1`, "");
  out.push(
    "Generated by `tools/extract` from the bytecode. Frame numbers are 1-based. Jumps that could not be folded into if/while blocks are left as `goto` with `L_xxxx:` labels. Expressions use the original (Flash 5) names, including slash syntax like `/:var` and `_root.x`.",
    "",
  );
  const block = (title: string, code: Uint8Array): void => {
    out.push(`### ${title}`, "", "```actionscript", decompile(code), "```", "");
  };

  out.push("## Root timeline", "");
  swf.root.frames.forEach((f, i) => {
    f.actions.forEach((a, k) => {
      block(
        `Frame ${i + 1}${f.label ? ` [${f.label}]` : ""}${f.actions.length > 1 ? ` (action ${k + 1})` : ""}`,
        a,
      );
    });
  });
  for (const ia of swf.initActions) block(`DoInitAction for sprite ${ia.spriteId}`, ia.code);

  out.push("## Sprites", "");
  for (const [id, ch] of [...swf.characters].sort((a, b) => a[0] - b[0])) {
    if (ch.type !== "sprite") continue;
    const labels = ch.timeline.frames
      .map((f, i) => (f.label ? `${i + 1}=${f.label}` : ""))
      .filter(Boolean);
    let wrote = false;
    ch.timeline.frames.forEach((f, i) => {
      f.actions.forEach((a, k) => {
        if (!wrote) {
          const where =
            sn.placements
              .get(id)
              ?.map((p) => `${p.parent} f${p.frame}`)
              .join(", ") ?? "unplaced";
          out.push(
            `### ${describeSprite(id, sn)}`,
            "",
            `Frames: ${ch.timeline.frames.length}. Labels: ${labels.join(", ") || "none"}. Placed in: ${where}.`,
            "",
          );
          wrote = true;
        }
        block(
          `${describeSprite(id, sn)} frame ${i + 1}${f.label ? ` [${f.label}]` : ""}${f.actions.length > 1 ? ` (action ${k + 1})` : ""}`,
          a,
        );
      });
    });
  }

  out.push("## Buttons", "");
  for (const [id, ch] of [...swf.characters].sort((a, b) => a[0] - b[0])) {
    if (ch.type !== "button" || ch.actions.length === 0) continue;
    const where =
      sn.placements
        .get(id)
        ?.map(
          (p) =>
            `${p.parent} f${p.frame} depth ${p.depth}${p.name ? ` '${p.name}'` : ""} at (${Math.round(p.at[0])}, ${Math.round(p.at[1])})`,
        )
        .join("; ") ?? "unplaced";
    out.push(`### Button ${id}`, "", `Placed: ${where}.`, "");
    for (const a of ch.actions) {
      if (a.code.length <= 1 && a.code[0] === 0) continue;
      block(`Button ${id} on (${condText(a.cond)})`, a.code);
    }
  }

  out.push("## Movie clip event handlers (onClipEvent)", "");
  const seen = (tl: TimelineData, parent: string): void => {
    tl.frames.forEach((f, fi) => {
      for (const c of f.cmds) {
        if (c.op !== "place" || !c.clipActions) continue;
        for (const ca of c.clipActions) {
          block(
            `${parent} frame ${fi + 1}, depth ${c.depth}${c.name ? ` '${c.name}'` : ""}: onClipEvent(${ca.events.join(", ")})`,
            ca.code,
          );
        }
      }
    });
  };
  seen(swf.root, "root");
  for (const [id, ch] of swf.characters)
    if (ch.type === "sprite") seen(ch.timeline, `sprite ${id}`);
  return out.join("\n");
}

/** Every string constant referenced by any action block. */
export function allActionStrings(swf: Swf): string[] {
  const set = new Set<string>();
  const add = (code: Uint8Array): void => {
    for (const s of stringsIn(code)) set.add(s);
  };
  const tl = (t: TimelineData): void => {
    for (const f of t.frames) {
      for (const a of f.actions) add(a);
      for (const c of f.cmds)
        if (c.op === "place" && c.clipActions) for (const ca of c.clipActions) add(ca.code);
    }
  };
  tl(swf.root);
  for (const ch of swf.characters.values()) {
    if (ch.type === "sprite") tl(ch.timeline);
    if (ch.type === "button") for (const a of ch.actions) add(a.code);
  }
  return [...set];
}

