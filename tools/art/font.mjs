function strokeToD(stroke, x0, y0, s) {
  const map = (p) => [x0 + p[0] * s, y0 + p[1] * s];
  if (Array.isArray(stroke)) {
    const pts = stroke.map(map);
    return `M${pts.map(([x, y]) => `${n(x)} ${n(y)}`).join("L")}`;
  }
  return smooth(stroke.s.map(map), false, 0.5);
}

/** Width of `text` in user units at cap height `size`. */
export function textWidth(text, size, track = 0.25) {
  const s = size / 6;
  let w = 0;
  for (const ch of text) {
    if (ch === " ") w += 2.4 * s;
    else w += ((G[ch]?.[0] ?? 3) + 1.1 + track) * s;
  }
  return w - (1.1 + track) * s;
}

/**
 * Path data for `text` with its top-left at (x, y), cap height `size`. `align` "middle" centres
 * on x. Returns { d, serifs } where serifs is extra path data for the serif ticks.
 */
export function textPath(text, x, y, size, { align = "start", track = 0.25, serif = false } = {}) {
  const s = size / 6;
  let cx = align === "middle" ? x - textWidth(text, size, track) / 2 : x;
  let d = "";
  let serifs = "";
  for (const ch of text.toUpperCase()) {
    if (ch === " ") {
      cx += 2.4 * s;
      continue;
    }
    const glyph = G[ch];
    if (!glyph) {
      cx += 3 * s;
      continue;
    }
    const [w, strokes] = glyph;
    for (const st of strokes) {
      d += strokeToD(st, cx, y, s);
      if (serif && Array.isArray(st)) {
        for (const p of [st[0], st[st.length - 1]]) {
          if (p[1] === 0 || p[1] === 6) {
            const px = cx + p[0] * s;
            const py = y + p[1] * s;
            serifs += `M${n(px - 0.55 * s)} ${n(py)}L${n(px + 0.55 * s)} ${n(py)}`;
          }
        }
      }
    }
    cx += (w + 1.1 + track) * s;
  }
  return { d, serifs };
}

/** A ready <path> of lettering. weight is stroke width as a fraction of cap height. */
export function lettering(text, x, y, size, color, o = {}) {
  const { weight = 0.14, align, track, serif, transform, opacity } = o;
  const { d, serifs } = textPath(text, x, y, size, { align, track, serif });
  const sw = n(size * weight, 2);
  const t = transform ? ` transform="${transform}"` : "";
  const op = opacity !== undefined ? ` opacity="${opacity}"` : "";
  return `<path d="${d}${serifs}" fill="none" stroke="${color}" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round"${t}${op}/>`;
}
